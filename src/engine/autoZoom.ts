import { CursorEvent, ZoomKeyframe } from '../types';

export interface CameraState {
  scale: number; // 1.0 = normal full screen, 1.5 - 2.5 = zoomed in
  centerX: number; // normalized center 0..1
  centerY: number; // normalized center 0..1
}

/**
 * Intelligent Auto-Zoom Engine.
 * Analyzes cursor telemetry (clicks, typing, gestures) and constructs cinematic camera paths.
 */
export class AutoZoomEngine {
  /**
   * Generates auto-zoom keyframes from a stream of cursor events.
   */
  public static generateKeyframes(
    events: CursorEvent[],
    totalDurationSeconds: number,
    options: {
      defaultScale?: number;
      transitionDuration?: number;
      holdDuration?: number;
      clusterTimeThreshold?: number; // seconds
      clusterDistThreshold?: number; // normalized distance
    } = {}
  ): ZoomKeyframe[] {
    const defaultScale = options.defaultScale ?? 2.0;
    const transitionDuration = options.transitionDuration ?? 0.45;
    const holdDuration = options.holdDuration ?? 1.4;
    const clusterTimeThreshold = options.clusterTimeThreshold ?? 2.2;
    const clusterDistThreshold = options.clusterDistThreshold ?? 0.35;

    if (!events || events.length === 0) return [];

    // Filter for action triggers: click, dblclick, mousedown
    const actionEvents = events.filter(
      (e) => e.type === 'click' || e.type === 'dblclick' || e.type === 'mousedown'
    );

    if (actionEvents.length === 0) return [];

    // Group close clicks into clusters
    interface ActionCluster {
      startTime: number; // seconds
      endTime: number;
      actions: CursorEvent[];
      targetX: number;
      targetY: number;
    }

    const clusters: ActionCluster[] = [];
    let currentCluster: ActionCluster | null = null;

    for (const ev of actionEvents) {
      const evSec = ev.timestamp / 1000;

      if (!currentCluster) {
        currentCluster = {
          startTime: Math.max(0, evSec - 0.3), // pre-roll 300ms before click
          endTime: evSec + holdDuration,
          actions: [ev],
          targetX: ev.x,
          targetY: ev.y,
        };
      } else {
        const timeDiff = evSec - (currentCluster.actions[currentCluster.actions.length - 1].timestamp / 1000);
        const dist = Math.hypot(ev.x - currentCluster.targetX, ev.y - currentCluster.targetY);

        if (timeDiff <= clusterTimeThreshold && dist <= clusterDistThreshold) {
          // Merge into current cluster, weighted towards latest action
          currentCluster.endTime = Math.max(currentCluster.endTime, evSec + holdDuration);
          currentCluster.actions.push(ev);
          // Gently shift focus towards subsequent clicks
          currentCluster.targetX = currentCluster.targetX * 0.4 + ev.x * 0.6;
          currentCluster.targetY = currentCluster.targetY * 0.4 + ev.y * 0.6;
        } else {
          clusters.push(currentCluster);
          currentCluster = {
            startTime: Math.max(0, evSec - 0.3),
            endTime: evSec + holdDuration,
            actions: [ev],
            targetX: ev.x,
            targetY: ev.y,
          };
        }
      }
    }

    if (currentCluster) {
      clusters.push(currentCluster);
    }

    // Convert clusters to ZoomKeyframes
    const rawKeyframes: ZoomKeyframe[] = [];

    clusters.forEach((cluster, idx) => {
      // Clamp bounds to valid video duration
      const startTime = Math.min(totalDurationSeconds - 0.5, Math.max(0, cluster.startTime));
      const endTime = Math.min(totalDurationSeconds, Math.max(startTime + 0.8, cluster.endTime));

      // Viewport safety clamp
      const clamped = AutoZoomEngine.clampCenter(cluster.targetX, cluster.targetY, defaultScale);

      rawKeyframes.push({
        id: `zoom_${idx}_${Math.floor(startTime * 1000)}`,
        startTime,
        endTime,
        targetX: clamped.x,
        targetY: clamped.y,
        scale: defaultScale,
        transitionDuration,
        easing: 'easeInOut',
        label: `Auto-Zoom #${idx + 1}`,
        isAutoGenerated: true,
      });
    });

    // Ensure non-overlapping, well-spaced keyframes
    const keyframes: ZoomKeyframe[] = [];
    for (const kf of rawKeyframes) {
      if (keyframes.length > 0) {
        const prev = keyframes[keyframes.length - 1];
        if (kf.startTime < prev.endTime + 0.1) {
          prev.endTime = Math.max(prev.startTime + 0.6, kf.startTime - 0.15);
        }
      }
      if (kf.endTime > kf.startTime + 0.4) {
        keyframes.push(kf);
      }
    }

    return keyframes;
  }

  /**
   * Clamps camera center so the scaled viewport never shows blank margins outside the video.
   */
  public static clampCenter(cx: number, cy: number, scale: number): { x: number; y: number } {
    if (scale <= 1.0) {
      return { x: 0.5, y: 0.5 };
    }

    const halfViewport = 0.5 / scale;
    const minCenter = halfViewport;
    const maxCenter = 1.0 - halfViewport;

    return {
      x: Math.min(maxCenter, Math.max(minCenter, cx)),
      y: Math.min(maxCenter, Math.max(minCenter, cy)),
    };
  }

  /**
   * Quintic ease in-out for ultra-smooth camera glide.
   */
  private static easeInOut(t: number): number {
    return t < 0.5 ? 16 * t * t * t * t * t : 1 - Math.pow(-2 * t + 2, 5) / 2;
  }

  /**
   * Computes the exact camera state { scale, centerX, centerY } at any given playback time `currentTimeSeconds`.
   */
  public static evaluateCamera(
    keyframes: ZoomKeyframe[],
    currentTimeSeconds: number
  ): CameraState {
    const defaultState: CameraState = {
      scale: 1.0,
      centerX: 0.5,
      centerY: 0.5,
    };

    if (!keyframes || keyframes.length === 0) {
      return defaultState;
    }

    // Find if we are currently inside or transitioning into/out of any keyframe
    for (let i = 0; i < keyframes.length; i++) {
      const kf = keyframes[i];
      const trans = Math.min(kf.transitionDuration, (kf.endTime - kf.startTime) / 2);

      const zoomInStart = kf.startTime;
      const zoomInEnd = kf.startTime + trans;
      const zoomOutStart = kf.endTime - trans;
      const zoomOutEnd = kf.endTime;

      if (currentTimeSeconds >= zoomInStart && currentTimeSeconds <= zoomOutEnd) {
        const targetClamp = AutoZoomEngine.clampCenter(kf.targetX, kf.targetY, kf.scale);

        if (currentTimeSeconds < zoomInEnd) {
          // Transitioning IN: 1.0 -> kf.scale
          const progress = Math.max(0, Math.min(1, (currentTimeSeconds - zoomInStart) / trans));
          const eased = AutoZoomEngine.easeInOut(progress);

          const scale = 1.0 + (kf.scale - 1.0) * eased;
          const cx = 0.5 + (targetClamp.x - 0.5) * eased;
          const cy = 0.5 + (targetClamp.y - 0.5) * eased;

          return { scale, centerX: cx, centerY: cy };
        } else if (currentTimeSeconds > zoomOutStart) {
          // Check if the next keyframe starts soon, allowing smooth pan directly to next target
          const nextKf = keyframes[i + 1];
          if (nextKf && nextKf.startTime <= zoomOutEnd + 0.3) {
            const nextTrans = Math.min(nextKf.transitionDuration, (nextKf.endTime - nextKf.startTime) / 2);
            const crossProgress = Math.max(0, Math.min(1, (currentTimeSeconds - zoomOutStart) / (nextKf.startTime + nextTrans - zoomOutStart)));
            const crossEased = AutoZoomEngine.easeInOut(crossProgress);
            const nextClamp = AutoZoomEngine.clampCenter(nextKf.targetX, nextKf.targetY, nextKf.scale);

            return {
              scale: kf.scale + (nextKf.scale - kf.scale) * crossEased,
              centerX: targetClamp.x + (nextClamp.x - targetClamp.x) * crossEased,
              centerY: targetClamp.y + (nextClamp.y - targetClamp.y) * crossEased,
            };
          }

          // Transitioning OUT: kf.scale -> 1.0
          const progress = Math.max(0, Math.min(1, (currentTimeSeconds - zoomOutStart) / trans));
          const eased = AutoZoomEngine.easeInOut(progress);

          const scale = kf.scale - (kf.scale - 1.0) * eased;
          const cx = targetClamp.x - (targetClamp.x - 0.5) * eased;
          const cy = targetClamp.y - (targetClamp.y - 0.5) * eased;

          return { scale, centerX: cx, centerY: cy };
        } else {
          // Fully zoomed in steady hold
          return {
            scale: kf.scale,
            centerX: targetClamp.x,
            centerY: targetClamp.y,
          };
        }
      }
    }

    return defaultState;
  }
}
