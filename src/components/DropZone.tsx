import React, { useState, useRef } from 'react';
import { UploadCloud, Film } from 'lucide-react';
import { RecordingSession, ZoomKeyframe } from '../types';

interface DropZoneProps {
  onVideoLoaded: (session: RecordingSession) => void;
  children: React.ReactNode;
}

export const DropZone: React.FC<DropZoneProps> = ({ onVideoLoaded, children }) => {
  const [isDragging, setIsDragging] = useState(false);
  const fileInputRef = useRef<HTMLInputElement | null>(null);

  const handleDragOver = (e: React.DragEvent) => {
    e.preventDefault();
    e.stopPropagation();
    setIsDragging(true);
  };

  const handleDragLeave = (e: React.DragEvent) => {
    e.preventDefault();
    e.stopPropagation();
    setIsDragging(false);
  };

  const handleDrop = (e: React.DragEvent) => {
    e.preventDefault();
    e.stopPropagation();
    setIsDragging(false);

    const files = e.dataTransfer.files;
    if (files && files.length > 0) {
      processFile(files[0]);
    }
  };

  const handleFileInputChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    const files = e.target.files;
    if (files && files.length > 0) {
      processFile(files[0]);
    }
  };

  const processFile = (file: File) => {
    if (!file.type.startsWith('video/') && !file.name.match(/\.(mp4|webm|mov|mkv)$/i)) {
      alert('Please upload a valid MP4 or WebM video file.');
      return;
    }

    const videoUrl = URL.createObjectURL(file);
    const tempVideo = document.createElement('video');
    tempVideo.preload = 'metadata';
    tempVideo.src = videoUrl;

    tempVideo.onloadedmetadata = () => {
      const duration = tempVideo.duration || 10;
      const width = tempVideo.videoWidth || 1920;
      const height = tempVideo.videoHeight || 1080;

      // Initial centered zoom keyframes
      const zoomKeyframes: ZoomKeyframe[] = [];
      if (duration > 3) {
        zoomKeyframes.push({
          id: `zoom_auto_${Date.now()}`,
          startTime: Math.min(1.5, duration * 0.2),
          endTime: Math.min(duration - 0.5, duration * 0.6),
          targetX: 0.5,
          targetY: 0.45,
          scale: 1.8,
          transitionDuration: 0.5,
          easing: 'easeInOut',
          label: 'Focal Zoom',
          isAutoGenerated: true,
        });
      }

      const session: RecordingSession = {
        id: `imported_${Date.now()}`,
        title: file.name,
        sourceWidth: width,
        sourceHeight: height,
        duration,
        videoUrl,
        videoBlob: file,
        cursorTelemetry: [
          { x: 0.5, y: 0.5, timestamp: 0, type: 'move' },
          { x: 0.5, y: 0.5, timestamp: Math.round(duration * 1000), type: 'move' },
        ],
        keystrokes: [],
        zoomKeyframes,
        inPoint: 0,
        outPoint: duration,
      };

      onVideoLoaded(session);
    };
  };

  return (
    <div
      onDragOver={handleDragOver}
      onDragLeave={handleDragLeave}
      onDrop={handleDrop}
      className="relative flex-1 flex flex-col h-full w-full overflow-hidden"
    >
      <input
        ref={fileInputRef}
        type="file"
        accept="video/mp4,video/webm,video/quicktime"
        className="hidden"
        onChange={handleFileInputChange}
      />

      {children}

      {/* Drag & Drop Visual Overlay */}
      {isDragging && (
        <div className="absolute inset-0 z-50 bg-neutral-950/85 backdrop-blur-md flex flex-col items-center justify-center p-8 border-2 border-dashed border-rose-500 m-4 rounded-3xl animate-in fade-in duration-200 pointer-events-none">
          <div className="w-16 h-16 rounded-2xl bg-rose-500/20 text-rose-400 flex items-center justify-center mb-4 shadow-xl shadow-rose-500/20 animate-bounce">
            <UploadCloud className="w-8 h-8" />
          </div>
          <h3 className="text-xl font-bold text-white mb-1">
            Drop Video to Import into ScreenForge
          </h3>
          <p className="text-sm text-neutral-400 text-center max-w-md">
            Instantly wraps your MP4, WebM or MOV recording into the 4K luxury studio canvas with
            auto-zoom and cursor physics.
          </p>
        </div>
      )}
    </div>
  );
};
