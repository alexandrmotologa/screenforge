export type AspectRatio = '16:9' | '9:16' | '1:1' | '4:3' | '4:5';

export type BackgroundTheme =
  | 'sunset'
  | 'cosmic'
  | 'emerald'
  | 'cyberpunk'
  | 'velvet'
  | 'obsidian'
  | 'slate'
  | 'clean-white'
  | 'custom';

export type CursorStyle = 'macos' | 'dark' | 'glow-ring' | 'neon-dot';

export type WindowFrameStyle = 'macOS' | 'sleek' | 'none';

export type ExportFormat = 'mp4' | 'webm' | 'gif';

export type ExportResolution = '4k' | '2k' | '1080p' | '720p';

export type WebcamPosition = 'bottom-right' | 'bottom-left' | 'top-right' | 'top-left';

export type ClickAudioStyle = 'mechanical' | 'soft' | 'minimal';

export interface CursorEvent {
  x: number; // 0 to 1 normalized, or absolute screen pixels
  y: number;
  timestamp: number; // ms from recording start
  type: 'move' | 'mousedown' | 'mouseup' | 'click' | 'dblclick' | 'contextmenu' | 'keydown';
  button?: number; // 0: left, 1: middle, 2: right
  key?: string;
  modifiers?: {
    ctrl?: boolean;
    shift?: boolean;
    alt?: boolean;
    meta?: boolean;
  };
}

export interface KeystrokeItem {
  id: string;
  key: string;
  modifiers: string[];
  timestamp: number; // ms
  duration: number; // ms to display
}

export interface ZoomKeyframe {
  id: string;
  startTime: number; // seconds
  endTime: number; // seconds
  targetX: number; // normalized center 0.0 - 1.0
  targetY: number; // normalized center 0.0 - 1.0
  scale: number; // e.g. 1.8x - 2.5x
  transitionDuration: number; // seconds for zoom in / out
  easing: 'spring' | 'easeInOut' | 'cubic';
  label?: string;
  isAutoGenerated?: boolean;
}

export interface StudioSettings {
  aspectRatio: AspectRatio;
  padding: number; // percentage or px inset (0 to 30)
  borderRadius: number; // px (0 to 40)
  shadowStrength: number; // 0 to 100
  shadowBlur: number; // px
  backgroundType: 'mesh' | 'solid' | 'gradient';
  backgroundTheme: BackgroundTheme;
  customBgColor: string;
  windowFrame: WindowFrameStyle;
  windowTitle: string;
  perspective3D: {
    enabled: boolean;
    rotateX: number; // -30 to 30 deg
    rotateY: number; // -30 to 30 deg
    rotateZ: number; // -20 to 20 deg
    depth: number; // px
  };
}

export interface CursorSettings {
  visible: boolean;
  smoothing: number; // 0 (raw) to 100 (maximum buttery spring)
  springStiffness: number; // e.g. 180
  springDamping: number; // e.g. 24
  springMass: number; // e.g. 1.0
  style: CursorStyle;
  size: number; // px (16 to 48)
  showRipples: boolean;
  rippleColor: string;
  tactileClickSound: boolean;
  clickSoundVolume: number;
}

export interface SpotlightSettings {
  enabled: boolean;
  intensity: number; // 0 to 100% dimming
  radius: number; // px radius of illuminated circle
}

export interface WebcamSettings {
  enabled: boolean;
  position: WebcamPosition;
  size: number; // px
  shape: 'circle' | 'squircle';
  borderWidth: number;
  borderColor: string;
  shadow: boolean;
}

export interface KeycastSettings {
  enabled: boolean;
  position: 'bottom-center' | 'top-center';
  style: 'glass' | 'dark' | 'glow';
  fadeDurationMs: number;
}

export interface IdleRampSettings {
  enabled: boolean;
  thresholdSeconds: number; // e.g. 2.5s
  speedMultiplier: number; // 2x or 4x
}

export interface ExportSettings {
  format: ExportFormat;
  resolution: ExportResolution;
  fps: 30 | 60;
  quality: 'ultra' | 'high' | 'balanced';
  engine: 'ffmpeg' | 'webcodecs';
}

export interface RecordingSession {
  id: string;
  title: string;
  sourceWidth: number;
  sourceHeight: number;
  duration: number; // seconds
  videoUrl: string;
  videoBlob?: Blob;
  cursorTelemetry: CursorEvent[];
  keystrokes: KeystrokeItem[];
  zoomKeyframes: ZoomKeyframe[];
  inPoint: number; // seconds (trim start)
  outPoint: number; // seconds (trim end)
}
